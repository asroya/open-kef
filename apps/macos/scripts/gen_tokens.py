#!/usr/bin/env python3
"""Generates Sources/OpenKef/Tokens.swift from design/tokens.json. Never hand-edit the output."""
import json, pathlib, sys
root = pathlib.Path(__file__).resolve().parents[3]
T = json.loads((root / 'design/tokens.json').read_text())
out = pathlib.Path(__file__).resolve().parents[1] / 'Sources/OpenKef/Tokens.swift'
W = {100:'.ultraLight',200:'.thin',300:'.light',400:'.regular',500:'.medium',600:'.semibold',700:'.bold',800:'.heavy',900:'.black'}
def hexc(h): return f'Color(hex: 0x{h.lstrip("#").upper()})'
L = [f'// GENERATED by apps/macos/scripts/gen_tokens.py from design/tokens.json v{T["$meta"]["version"]}. Do not edit.',
     'import SwiftUI', '', 'enum T {',
     f'    static let version = "{T["$meta"]["version"]}"', '',
     '    struct Palette {']
keys = list(T['color']['light'])
L += [f'        let {k}: Color' for k in keys] + ['    }']
for mode in ('light','dark'):
    args = ', '.join(f'{k}: {hexc(T["color"][mode][k])}' for k in keys)
    L.append(f'    static let {mode} = Palette({args})')
L += ['', '    struct TypeStyle { let size: CGFloat; let weight: Font.Weight; let tracking: CGFloat; let lineHeight: CGFloat; let tabular: Bool }',
      '    enum TypeScale {']
for k, t in T['type'].items():
    L.append(f'        static let {k} = TypeStyle(size: {t["size"]}, weight: {W[t["weight"]]}, tracking: {t["tracking"]}, lineHeight: {t["lineHeight"]}, tabular: {"true" if "tnum" in t.get("features", []) else "false"})')
L.append('    }')
def group(name, d, prefix=''):
    L.append(f'    enum {name} {{')
    for k, v in d.items():
        if isinstance(v, (int, float)): L.append(f'        static let {prefix}{k}: CGFloat = {v}')
    L.append('    }')
group('Space', T['space'], 's'); group('Radius', T['radius']); group('Size', T['size'])
L.append('    enum Icon {'); L.append(f'        static let size: CGFloat = {T["icon"]["size"]}')
L.append(f'        static let weight: Font.Weight = .{T["icon"]["weight"]}'); L.append('    }')
L.append('    enum Focus {'); L.append(f'        static let width: CGFloat = {T["focus"]["width"]}  // HTML mockups + snapshot spinner stand-in only'); L.append('    }')
r = T['ruler']; pd = T['pending']
def role(ref): return ref.split('.')[-1]  # "color.*.text" -> palette key
assert pd['underline'] == 'dotted', 'add a mapping for new underline patterns'
L += ['    enum Ruler {', f'        static let tickWidth: CGFloat = {r["tickWidth"]}', f'        static let majorEvery = {r["majorEvery"]}',
      f'        static func filled(_ p: Palette) -> Color {{ p.{role(r["tickFilled"])} }}',
      f'        static func minor(_ p: Palette) -> Color {{ p.{role(r["tickMinor"])} }}',
      f'        static func major(_ p: Palette) -> Color {{ p.{role(r["tickMajor"])} }}', '    }',
      '    enum Pending {', f'        static let width: CGFloat = {pd["width"]}',
      f'        static func textColor(_ p: Palette) -> Color {{ p.{role(pd["textColor"])} }}', f'        static func underlineColor(_ p: Palette) -> Color {{ p.{role(pd["underlineColor"])} }}', '    }']
L.append('    enum Opacity {'); L.append(f'        static let disabled: Double = {T["opacity"]["disabled"]}'); L.append('    }')
m = T['motion']
assert m['easing'] == 'easeOut', 'add a mapping for new easing values'
L += ['    enum Motion {', f'        static let fast: Double = {m["fast"]} / 1000', f'        static let base: Double = {m["base"]} / 1000',
      '        static func easing(_ d: Double) -> Animation { .easeOut(duration: d) }', '    }', '}', '',
      'extension Color {', '    init(hex: UInt32) {',
      '        self.init(.sRGB, red: Double((hex >> 16) & 0xFF) / 255, green: Double((hex >> 8) & 0xFF) / 255, blue: Double(hex & 0xFF) / 255, opacity: 1)',
      '    }', '}', '']
src = '\n'.join(L)
if '--check' in sys.argv:
    sys.exit(0 if out.exists() and out.read_text() == src else 'Tokens.swift is stale: run apps/macos/scripts/gen_tokens.py')
out.write_text(src)
print(f'wrote {out}')
